"""Domain contracts; the engine has no block-specific knowledge."""
from typing import Protocol
from .logic import Fact


class DomainHooks(Protocol):
    derived_predicates: frozenset[str]
    derived_basis: dict[str, frozenset[str]]
    resource_predicates: frozenset[str]

    def evaluate(self, pred: str, args: tuple[str, ...], state: frozenset[Fact]) -> bool: ...
    def invariant(self, state: frozenset[Fact]) -> str | None: ...
    def expand(self, fact: Fact) -> list[Fact]: ...
    def justify(self, fact: Fact, state: frozenset[Fact]) -> list[Fact]: ...
    def invariant_needs(self, action) -> list[Fact]: ...
    def position(self, place: str) -> tuple[float, float, float]: ...
    def speed(self, arm: str) -> float: ...
    def scene_summary(self) -> list[str]: ...
